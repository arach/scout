/** Distance as a ratio, because "0.0004x" reads as noise and "1:2,500" reads as far. */
function formatZoom(zoom: number) {
  if (zoom >= 1) return `${Number(zoom.toFixed(zoom < 10 ? 1 : 0))}:1`;
  return `1:${Math.round(1 / zoom).toLocaleString()}`;
}


