// ---------------------------------------------------------------------------
// Claude Code prompt markup.
//
// Claude Code writes its own markup into user turns: background task
// notifications, slash command echoes and their output, `!` shell lines,
// system reminders, page context from the desktop app, pasted blocks,
// continuation summaries and skill bodies. This file is the one place that
// knows those shapes; it returns protocol PromptParts so nothing downstream
// parses Claude Code's text.
//
// Unknown wrapper elements (see prompt-markup-scan.ts) become context parts,
// never prose, so a new harness tag shows up as a label instead of leaking
// its body.
// ---------------------------------------------------------------------------

import {
  classifiedPrompt,
  type ClassifiedPrompt,
  type PromptCommandPart,
  type PromptPart,
} from "../../protocol/prompt-parts.js";
import { markupChildren, markupLabel, nextMarkupElement, type MarkupElement } from "../prompt-markup-scan.js";

/** Labels for context wrappers Claude Code is known to inject. */
const CONTEXT_LABELS: Record<string, string> = {
  "system-reminder": "Reminder",
  "local-command-caveat": "Command note",
  "artifact-view-context": "Artifact view",
  "artifact-content-authored-by-others": "Shared content note",
  "in-app-browser-context": "Browser context",
  "environment_context": "Environment",
  "app-context": "App context",
  "user-prompt-submit-hook": "Hook",
  "ide_selection": "Editor selection",
  "ide_opened_file": "Open file",
  "side-sessions-event": "Side sessions",
};

const COMMAND_TAGS = new Set(["command-name", "command-message", "command-args", "skill-format"]);
/** Another session's words handed into this one: a subagent's report, or a
 *  peer session's message. Claude Code leads each with SESSION_LEAD. */
const SESSION_TAGS: Record<string, string> = { "agent-message": "subagent", "cross-session-message": "session" };
const SESSION_LEAD = /\s*Another Claude session sent a message:\s*$/;
const OUTPUT_TAGS: Record<string, { stream: "stdout" | "stderr"; from: "command" | "shell" }> = {
  "local-command-stdout": { stream: "stdout", from: "command" },
  "local-command-stderr": { stream: "stderr", from: "command" },
  "bash-stdout": { stream: "stdout", from: "shell" },
  "bash-stderr": { stream: "stderr", from: "shell" },
};
const SPECIAL_TAGS = new Set(["task-notification", "pasted_content", "bash-input", ...COMMAND_TAGS, ...Object.keys(OUTPUT_TAGS), ...Object.keys(SESSION_TAGS)]);

const CONTINUATION = /^This session is being continued from a previous conversation\b/m;
const SKILL = /^Base directory for this skill:\s*(\S+)/;
/** Older Claude Code wrote the local-command caveat as bare text. */
const CAVEAT = /^Caveat: The messages below were generated by the user while running local commands\b/;
const INTERRUPTED = /^\[Request interrupted by user(?: for tool use)?\]$/;

const SCAN = { isKnown: (name: string) => name in CONTEXT_LABELS || SPECIAL_TAGS.has(name) };

function taskNotification(body: string): PromptPart {
  const fields = markupChildren(body);
  const summary = fields.summary || "Background task finished";
  const refs: Record<string, string> = {};
  if (fields["task-id"]) refs.taskId = fields["task-id"];
  if (fields["tool-use-id"]) refs.toolUseId = fields["tool-use-id"];
  if (fields["output-file"]) refs.outputFile = fields["output-file"];
  const title = summary.match(/"([^"]+)"/)?.[1];
  return {
    kind: "notice",
    source: "task",
    summary,
    ...(fields.status ? { status: fields.status } : {}),
    ...(title ? { title } : {}),
    ...(Object.keys(refs).length ? { refs } : {}),
  };
}

function sessionMessage(element: MarkupElement): PromptPart {
  const text = element.body.trim();
  // Skip the hand-back frame Claude Code puts ahead of a subagent's report.
  const lines = text.split("\n").map((line) => line.trim()).filter(Boolean);
  const first = lines.find((line) => !/^\[Subagent hand-back\]/.test(line)) ?? lines[0] ?? "";
  const from = element.attrs["from-name"] ?? element.attrs.from;
  const refs: Record<string, string> = {};
  if (element.attrs.from) refs.from = element.attrs.from;
  return {
    kind: "notice",
    source: SESSION_TAGS[element.name]!,
    summary: first.length > 200 ? `${first.slice(0, 199)}…` : first,
    ...(from ? { title: from } : {}),
    ...(Object.keys(refs).length ? { refs } : {}),
    ...(text ? { text } : {}),
  };
}

function contextPart(element: MarkupElement): PromptPart {
  const detail = element.attrs.source ?? element.attrs.artifact ?? Object.values(element.attrs)[0];
  const text = element.body.trim();
  return {
    kind: "context",
    name: element.name,
    label: CONTEXT_LABELS[element.name] ?? markupLabel(element.name),
    ...(detail ? { detail } : {}),
    ...(text ? { text } : {}),
  };
}

/** Words between elements, unless a preamble claims the rest of the turn.
 *  `previous` is the part just before the chunk: a bodiless note (Claude Code
 *  writes `<artifact-content-authored-by-others/>` and then its explanation
 *  as bare text) takes the text ahead of a continuation summary as its own. */
function wordsOrPreamble(chunk: string, rest: string, previous: PromptPart | undefined): { parts: PromptPart[]; consumeRest: boolean } {
  const trimmed = chunk.trim();
  if (!trimmed) return { parts: [], consumeRest: false };
  const continuation = CONTINUATION.exec(trimmed);
  if (continuation) {
    const parts: PromptPart[] = [];
    const before = trimmed.slice(0, continuation.index).trim();
    if (before && previous?.kind === "context" && !previous.text) previous.text = before;
    else if (before) parts.push({ kind: "words", text: before });
    parts.push({ kind: "context", name: "continuation", label: "Earlier conversation", text: (trimmed.slice(continuation.index) + rest).trim() });
    return { parts, consumeRest: true };
  }
  const skill = trimmed.match(SKILL);
  if (skill) {
    const name = skill[1]!.replace(/\/+$/, "").split("/").at(-1);
    return { parts: [{ kind: "context", name: "skill", label: "Skill", ...(name ? { detail: name } : {}), text: (trimmed + rest).trim() }], consumeRest: true };
  }
  if (CAVEAT.test(trimmed)) return { parts: [{ kind: "context", name: "local-command-caveat", label: "Command note", text: trimmed }], consumeRest: false };
  if (INTERRUPTED.test(trimmed)) return { parts: [{ kind: "notice", source: "interrupt", summary: "Interrupted" }], consumeRest: false };
  return { parts: [{ kind: "words", text: trimmed }], consumeRest: false };
}

export interface ClaudeCodePromptOptions {
  /** The transcript entry's `isMeta` flag: Claude Code wrote this turn itself
   *  (an expanded slash command body, a hand-off), so bare text in it is not
   *  the operator's. */
  meta?: boolean;
}

/** Split a Claude Code user turn into the operator's words and Claude Code's markup. */
export function classifyClaudeCodePrompt(text: string, options: ClaudeCodePromptOptions = {}): ClassifiedPrompt {
  const result = classifyMarkup(text);
  if (!options.meta || !result.parts.some((part) => part.kind === "words")) return result;
  return classifiedPrompt(result.parts.map((part) => part.kind === "words"
    ? { kind: "context", name: "harness-text", label: "Added by Claude Code", text: part.text }
    : part));
}

function classifyMarkup(text: string): ClassifiedPrompt {
  const parts: PromptPart[] = [];
  let command: PromptCommandPart | null = null;
  let commandMessage: string | undefined;
  const flushCommand = () => {
    if (command || commandMessage) parts.push(command ?? { kind: "command", name: `/${commandMessage}` });
    command = null;
    commandMessage = undefined;
  };

  let cursor = 0;
  while (cursor < text.length) {
    const element = nextMarkupElement(text, cursor, SCAN);
    let chunk = text.slice(cursor, element ? element.start : text.length);
    if (element && element.name in SESSION_TAGS) chunk = chunk.replace(SESSION_LEAD, "");
    if (chunk.trim()) {
      flushCommand();
      const { parts: chunkParts, consumeRest } = wordsOrPreamble(chunk, element ? text.slice(element.start) : "", parts.at(-1));
      parts.push(...chunkParts);
      if (consumeRest) return classifiedPrompt(parts);
    }
    if (!element) break;
    cursor = element.end;

    const { name, body } = element;
    if (COMMAND_TAGS.has(name)) {
      const value = body.trim();
      if (name === "command-name") {
        if (command) flushCommand();
        command = { kind: "command", name: value };
      } else if (name === "command-args") {
        if (value) command = { ...(command ?? { kind: "command", name: commandMessage ? `/${commandMessage}` : "" }), args: value };
      } else if (name === "command-message") {
        commandMessage = value;
      }
      continue;
    }
    flushCommand();
    if (name === "task-notification") parts.push(taskNotification(body));
    else if (name in SESSION_TAGS) parts.push(sessionMessage(element));
    else if (name === "pasted_content") {
      const pasted = body.replace(/^\n+|\s+$/g, "");
      if (pasted) parts.push({ kind: "paste", text: pasted, ...(element.attrs.id ? { id: element.attrs.id } : {}) });
    } else if (name === "bash-input") parts.push({ kind: "command", name: body.trim(), shell: true });
    else if (name in OUTPUT_TAGS) {
      const output = body.trim();
      if (output) parts.push({ kind: "output", ...OUTPUT_TAGS[name]!, text: output });
    } else parts.push(contextPart(element));
  }
  flushCommand();
  return classifiedPrompt(parts);
}
